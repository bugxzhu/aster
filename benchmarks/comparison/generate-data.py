#!/usr/bin/env python3
"""Generate the Tauri app's data files from the Aster sources, so both implementations share
exactly the same mock rows and locale strings.

Sources:
  spikes/file-manager-core/src/mock.rs   (23 rows of name, kind, modified)
  locales/en.toml, locales/zh-CN.toml    (ui strings)
Output:
  benchmarks/apps/tauri-file-manager/src/data.js
"""
import json
import pathlib
import re
import tomllib

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "benchmarks/apps/tauri-file-manager/src"

def unescape_rust(s: str) -> str:
    return re.sub(r"\\u\{([0-9A-Fa-f]+)\}", lambda m: chr(int(m.group(1), 16)), s)

def mock_rows() -> list:
    text = (ROOT / "spikes/file-manager-core/src/mock.rs").read_text(encoding="utf-8")
    # rustfmt may wrap a tuple over several lines, so whitespace (including newlines) is allowed
    # between the parts. The array length declared in mock.rs is the expected row count.
    declared = int(re.search(r"let rows: \[\(&str, &str, &str\); (\d+)\]", text).group(1))
    rows = re.findall(
        r'\(\s*"((?:[^"\\]|\\.)*)",\s*"((?:[^"\\]|\\.)*)",\s*"((?:[^"\\]|\\.)*)",?\s*\)', text)
    assert len(rows) == declared, f"parsed {len(rows)} rows, mock.rs declares {declared}"
    return [{"name": unescape_rust(n), "kind": k, "modified": m} for n, k, m in rows]

def locale(tag: str) -> dict:
    data = tomllib.loads((ROOT / f"locales/{tag}.toml").read_text(encoding="utf-8"))
    return data["ui"]

def main() -> None:
    rows = mock_rows()
    body = (
        "// Generated by benchmarks/comparison/generate-data.py. Do not edit by hand.\n"
        f"export const files = {json.dumps(rows, ensure_ascii=False, indent=2)};\n"
        f"export const locales = {json.dumps({'en': locale('en'), 'zh-CN': locale('zh-CN')}, ensure_ascii=False, indent=2)};\n"
    )
    (ROOT / "benchmarks/apps/tauri-file-manager/src/data.js").write_text(body, encoding="utf-8")
    print(f"wrote {len(rows)} rows and 2 locales to {OUT / 'data.js'}")

if __name__ == "__main__":
    main()
